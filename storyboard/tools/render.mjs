// Storyboard renderer. Drives headless Chrome over the DevTools protocol,
// screenshots every frame at native size, measures its colour budget, and
// checks that text stays inside the frame.
//
//   node storyboard/tools/render.mjs            # every scene
//   node storyboard/tools/render.mjs S02 S03    # only these scenes
//   node storyboard/tools/render.mjs --collect  # rebuild storyboard/measure.js only
//
// Output: storyboard/frames/<id>-<frame>-<desktop|phone>.png
//         storyboard/frames/measure-<id>.json  (one per scene)
//         storyboard/measure.js                (all scenes, read by the review page)
import { spawn } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SB = path.resolve(HERE, "..");
const OUT = path.join(SB, "frames");
fs.mkdirSync(OUT, { recursive: true });
const CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
const SIZES = { desktop: [1440, 900], phone: [375, 812] };

const args = process.argv.slice(2);
if (args.includes("--collect")) {
  collect();
  process.exit(0);
}
const only = args.filter((a) => /^S\d\d|^H/.test(a));

/* ── PNG decode (8-bit RGB/RGBA, non-interlaced) ─────────────────── */
function decodePNG(buf) {
  let p = 8, w = 0, h = 0, ct = 0;
  const idat = [];
  while (p < buf.length) {
    const len = buf.readUInt32BE(p);
    const type = buf.toString("ascii", p + 4, p + 8);
    const data = buf.subarray(p + 8, p + 8 + len);
    if (type === "IHDR") { w = data.readUInt32BE(0); h = data.readUInt32BE(4); ct = data[9]; }
    else if (type === "IDAT") idat.push(data);
    p += 12 + len;
  }
  const bpp = ct === 6 ? 4 : 3;
  const raw = zlib.inflateSync(Buffer.concat(idat));
  const stride = w * bpp;
  const px = Buffer.alloc(h * stride);
  for (let y = 0; y < h; y++) {
    const f = raw[y * (stride + 1)];
    const src = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    for (let x = 0; x < stride; x++) {
      const a = x >= bpp ? px[y * stride + x - bpp] : 0;
      const b = y > 0 ? px[(y - 1) * stride + x] : 0;
      const c = x >= bpp && y > 0 ? px[(y - 1) * stride + x - bpp] : 0;
      let v = src[x];
      if (f === 1) v += a;
      else if (f === 2) v += b;
      else if (f === 3) v += (a + b) >> 1;
      else if (f === 4) { const pp = a + b - c, pa = Math.abs(pp - a), pb = Math.abs(pp - b), pc = Math.abs(pp - c); v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c; }
      px[y * stride + x] = v & 255;
    }
  }
  return { w, h, bpp, px };
}
// Share of the frame in each brand colour family.
function measure(buf) {
  const { w, h, bpp, px } = decodePNG(buf);
  const n = w * h;
  const k = { red: 0, ember: 0, blue: 0, deep: 0, off: 0 };
  for (let i = 0; i < n; i++) {
    const r = px[i * bpp], g = px[i * bpp + 1], b = px[i * bpp + 2];
    const mx = Math.max(r, g, b), mn = Math.min(r, g, b);
    if (r >= 150 && r - g >= 80 && r - b >= 80) k.red++;
    else if (r >= 80 && r - g >= 45 && r - b >= 45) k.ember++;
    else if (b >= 150 && b - r >= 80) k.blue++;
    else if (b >= 45 && b - r >= 30 && b - g >= 12) k.deep++;
    else if (mx - mn >= 60) k.off++;
  }
  const pct = (v) => Math.round((v / n) * 10000) / 100;
  return { red: pct(k.red), ember: pct(k.ember), blue: pct(k.blue), deep: pct(k.deep), off: pct(k.off) };
}

function collect() {
  const all = {};
  for (const f of fs.readdirSync(OUT)) if (/^measure-.*\.json$/.test(f)) Object.assign(all, JSON.parse(fs.readFileSync(path.join(OUT, f), "utf8")));
  fs.writeFileSync(path.join(SB, "measure.js"), "/* generated by tools/render.mjs */\nwindow.SB_MEASURE = " + JSON.stringify(all, null, 0) + ";\n");
  console.log("measure.js: " + Object.keys(all).length + " frames");
}

/* ── Chrome over CDP ─────────────────────────────────────────────── */
const port = 9300 + Math.floor(Math.random() * 600);
const userDir = fs.mkdtempSync(path.join(os.tmpdir(), "sb-chrome-"));
const chrome = spawn(CHROME, ["--headless=new", `--remote-debugging-port=${port}`, "--hide-scrollbars", "--no-first-run", "--no-default-browser-check", `--user-data-dir=${userDir}`, "--allow-file-access-from-files", "--force-color-profile=srgb", "--font-render-hinting=none", "about:blank"], { stdio: "ignore" });
const cleanup = () => { try { chrome.kill("SIGKILL"); } catch {} try { fs.rmSync(userDir, { recursive: true, force: true }); } catch {} };
process.on("exit", cleanup);

async function pageTarget() {
  for (let i = 0; i < 150; i++) {
    try {
      const j = await (await fetch(`http://127.0.0.1:${port}/json/list`)).json();
      const pg = j.find((t) => t.type === "page");
      if (pg) return pg;
    } catch {}
    await new Promise((r) => setTimeout(r, 100));
  }
  throw new Error("Chrome did not start");
}
const target = await pageTarget();
const ws = new WebSocket(target.webSocketDebuggerUrl);
await new Promise((res, rej) => { ws.onopen = res; ws.onerror = rej; });
let seq = 0;
const pending = new Map();
const listeners = new Set();
ws.onmessage = (ev) => {
  const m = JSON.parse(ev.data);
  if (m.id && pending.has(m.id)) { const { res, rej } = pending.get(m.id); pending.delete(m.id); m.error ? rej(new Error(m.error.message)) : res(m.result); }
  else if (m.method) for (const l of listeners) l(m);
};
const send = (method, params = {}) => new Promise((res, rej) => { const id = ++seq; pending.set(id, { res, rej }); ws.send(JSON.stringify({ id, method, params })); });
const waitEvent = (name, ms = 20000) => new Promise((res, rej) => {
  const t = setTimeout(() => { listeners.delete(l); rej(new Error("timeout " + name)); }, ms);
  const l = (m) => { if (m.method === name) { clearTimeout(t); listeners.delete(l); res(m.params); } };
  listeners.add(l);
});
await send("Page.enable");
await send("Runtime.enable");
const consoleErrors = [];
listeners.add((m) => { if (m.method === "Runtime.exceptionThrown") consoleErrors.push(m.params.exceptionDetails?.exception?.description || m.params.exceptionDetails?.text); });

const frameURL = (q) => pathToFileURL(path.join(SB, "frame.html")).href + "?" + new URLSearchParams(q).toString();
async function load(q, w, h) {
  await send("Emulation.setDeviceMetricsOverride", { width: w, height: h, deviceScaleFactor: 1, mobile: false });
  const ev = waitEvent("Page.loadEventFired");
  await send("Page.navigate", { url: frameURL(q) });
  await ev;
  const r = await send("Runtime.evaluate", { expression: "(window.__SB_READY||Promise.resolve(null)).then(function(r){return JSON.stringify(r)})", awaitPromise: true, returnByValue: true });
  return r.result.value ? JSON.parse(r.result.value) : null;
}

// Scene list
await load({ s: "__list" }, 400, 300);
const list = JSON.parse((await send("Runtime.evaluate", { expression: "JSON.stringify(SB.scenes.map(function(s){return {id:s.id,frames:s.frames.map(function(f){return f.k}),alts:s.alts.map(function(a){return {k:a.k,frames:a.frames||s.frames.map(function(f){return f.k})}}),screens:s.screens}}))", returnByValue: true })).result.value);
const todo = list.filter((s) => !only.length || only.includes(s.id));
if (!todo.length) { console.log("No matching scenes. Loaded: " + list.map((s) => s.id).join(", ")); cleanup(); process.exit(1); }

let problems = 0;
for (const s of todo) {
  const jobs = [];
  for (const v of ["desktop", "phone"]) {
    for (const f of s.frames) jobs.push({ q: { s: s.id, f, v }, name: `${s.id}-${f}-${v}` });
    jobs.push({ q: { s: s.id, f: "plate", v, plate: "1" }, name: `${s.id}-plate-${v}` });
    for (const a of s.alts) for (const f of a.frames) jobs.push({ q: { s: s.id, f, v, alt: a.k }, name: `${s.id}-${f}-alt${a.k}-${v}` });
  }
  const results = {};
  for (const j of jobs) {
    const [w, h] = SIZES[j.q.v];
    consoleErrors.length = 0;
    let rep;
    try { rep = await load(j.q, w, h); } catch (e) { rep = { error: String(e) }; }
    const shot = await send("Page.captureScreenshot", { format: "png", clip: { x: 0, y: 0, width: w, height: h, scale: 1 } });
    const buf = Buffer.from(shot.data, "base64");
    fs.writeFileSync(path.join(OUT, j.name + ".png"), buf);
    const m = measure(buf);
    const log = rep && rep.log;
    const rungBad = log ? log.rungs.filter((r) => Math.abs(r.err) > 0.02) : [];
    const res = {
      ...m,
      overflow: (rep && rep.overflow) || [],
      error: (rep && rep.error) || (consoleErrors.length ? consoleErrors.join(" | ") : null),
      flags: log ? log.flags : [],
      figs: log ? log.figs.map((f) => f.shown + " ← " + f.path) : [],
      rungErr: log ? log.rungs.map((r) => ({ path: r.path, err: Math.round(r.err * 10000) / 100 })) : [],
    };
    results[j.name] = res;
    const bad = res.error || res.overflow.length || rungBad.length || res.off > 0.2;
    if (bad) problems++;
    console.log(
      (bad ? "✗ " : "✓ ") + j.name.padEnd(28) +
      ` red ${m.red}%  blue ${m.blue}%  ember ${m.ember}%  deep ${m.deep}%  off-brand ${m.off}%` +
      (res.error ? "\n    ERROR: " + res.error.split("\n")[0] : "") +
      (res.overflow.length ? "\n    OVERFLOW: " + JSON.stringify(res.overflow) : "") +
      (rungBad.length ? "\n    RUNG AREA OFF >2%: " + JSON.stringify(rungBad) : "") +
      (res.flags.length ? "\n    flags: " + res.flags.map((f) => f.kind + ": " + f.text).join(" | ") : "")
    );
  }
  fs.writeFileSync(path.join(OUT, `measure-${s.id}.json`), JSON.stringify(results));
}
collect();
console.log(problems ? `\n${problems} frame(s) need attention.` : "\nAll frames clean.");
cleanup();
process.exit(0);
